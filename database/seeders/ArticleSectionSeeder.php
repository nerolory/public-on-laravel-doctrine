    /**
     * Создаёт разделы, которых ещё нет, и раскладывает статьи по разделам из дерева.
     */
    public function run(ArticleSectionService $sections): void
    {
        foreach (self::TREE as $rootName => $root) {
            $rootSection = $this->section($sections, $rootName);
            $sections->assignToArticles($rootSection, collect($root['articles']));

            foreach ($root['children'] as $childName => $titles) {
                $sections->assignToArticles($this->section($sections, $childName, $rootSection), collect($titles));
            }
        }
    }

    /**
     * Раздел по названию; если его нет, создаётся внутри родительского.
     */
    private function section(
        ArticleSectionService $sections,
        string $name,
        ?ArticleSection $parent = null,
    ): ArticleSection {
        return $sections->findByName($name) ?? $sections->create($name, $parent?->getId());
    }
